// Moving and still pictures of the landscapes (looping videos and their posters).
// Content keys follow the API contract § 8; bundled copies live in assets/landscapes/.

/// Where the looping video of a landscape is played from.
sealed class LandscapeVideoSource {
  const LandscapeVideoSource();
}

/// Bundled with the app (`assets/landscapes/<id>.mp4`): free landscapes, and every landscape
/// with a video in the demo build.
final class AssetLandscapeVideo extends LandscapeVideoSource {
  const AssetLandscapeVideo(this.asset);

  final String asset;

  @override
  bool operator ==(Object other) =>
      other is AssetLandscapeVideo && other.asset == asset;

  @override
  int get hashCode => asset.hashCode;

  @override
  String toString() => 'AssetLandscapeVideo($asset)';
}

/// Downloaded once from the content server and kept on the phone (Premium).
final class FileLandscapeVideo extends LandscapeVideoSource {
  const FileLandscapeVideo(this.path);

  final String path;

  @override
  bool operator ==(Object other) =>
      other is FileLandscapeVideo && other.path == path;

  @override
  int get hashCode => path.hashCode;

  @override
  String toString() => 'FileLandscapeVideo($path)';
}

/// Content keys (S3, `POST /content/urls`) and bundled asset paths of landscape media.
abstract final class LandscapeMediaKeys {
  /// `videos/paysages/<id>.mp4`: seamless loop, H.264, no audio.
  static String video(String id) => 'videos/paysages/$id.mp4';

  /// `images/paysages/<id>.jpg`: poster, exactly the first frame of the loop.
  static String image(String id) => 'images/paysages/$id.jpg';

  static String bundledVideo(String id) => 'assets/landscapes/$id.mp4';
  static String bundledImage(String id) => 'assets/landscapes/$id.jpg';

  /// Generated by tools/media/process_video.py: which Premium landscapes have a video or an
  /// image on the content server, so that the app never asks for a missing key.
  static const String remoteManifest = 'assets/landscapes/remote.json';
}

/// Contents of [LandscapeMediaKeys.remoteManifest]: `{"version": 1, "videos": [...],
/// "images": [...], "sons": [...], "musiques": [...]}` (written by tools/media/remote_manifest.py
/// from `content/`).
class RemoteLandscapeMedia {
  const RemoteLandscapeMedia({this.videos = const {}, this.images = const {}, this.sounds, this.music});

  final Set<String> videos;
  final Set<String> images;

  /// `audio/sons/<id>.ogg` on the content server (sounds, landscape ambiances, variants of the
  /// event sounds). Null when the manifest has no such list: every catalog sound is assumed there.
  final Set<String>? sounds;

  /// `audio/musiques/<id>.ogg` on the content server; null: every catalog music is assumed there.
  final Set<String>? music;

  static const RemoteLandscapeMedia none = RemoteLandscapeMedia();

  /// Lenient: anything unexpected means « nothing on the server » (and no list of audio files).
  factory RemoteLandscapeMedia.fromJson(Object? json) {
    if (json is! Map) return none;
    Set<String> ids(Object? list) => {
      if (list is List)
        for (final id in list)
          if (id is String && RegExp(r'^[a-z0-9-]{1,64}$').hasMatch(id)) id,
    };
    Set<String>? audio(Object? list) => list is List ? ids(list) : null;
    return RemoteLandscapeMedia(
      videos: ids(json['videos']),
      images: ids(json['images']),
      sounds: audio(json['sons']),
      music: audio(json['musiques']),
    );
  }
}
