def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, check=True, **kw)


@dataclass
class Probe:
    index: int
    width: int
    height: int
    fps: Fraction
    pix_fmt: str
    space: str
    primaries: str
    trc: str
    range: str


def probe(path: Path) -> Probe:
    out = run(
        ["ffprobe", "-v", "error", "-show_entries",
         "stream=index,codec_type,width,height,r_frame_rate,pix_fmt,color_space,"
         "color_primaries,color_transfer,color_range:stream_disposition=attached_pic",
         "-of", "json", str(path)],
        capture_output=True,
    ).stdout
    for s in json.loads(out)["streams"]:
        # Skip embedded cover pictures (PNG/JPEG "attached_pic" video streams).
        if s.get("codec_type") != "video" or s.get("disposition", {}).get("attached_pic"):
            continue
        return Probe(
            index=int(s["index"]),
            width=int(s["width"]),
            height=int(s["height"]),
            fps=Fraction(s["r_frame_rate"]),
            pix_fmt=s.get("pix_fmt", ""),
            space=s.get("color_space", "unknown"),
            primaries=s.get("color_primaries", "unknown"),
            trc=s.get("color_transfer", "unknown"),
            range=s.get("color_range", "tv"),
        )
    raise SystemExit(f"{path}: no video stream")


def matrix_of(space: str) -> str:
    """Output colour matrix: the source's (data is never re-matrixed)."""
    return "bt709" if space == "bt709" else "smpte170m"


def sws_matrix(space: str) -> str:
    return "bt709" if space == "bt709" else "bt601"


class Planes:
    """yuv420p frames as three uint8 arrays: Y (n, h, w), U and V (n, h/2, w/2)."""

    def __init__(self, y: np.ndarray, u: np.ndarray, v: np.ndarray):
        self.y, self.u, self.v = y, u, v

    @property
    def n(self) -> int:
        return self.y.shape[0]

    @property
    def size(self) -> tuple[int, int]:
        return self.y.shape[2], self.y.shape[1]

    def take(self, idx) -> "Planes":
        return Planes(self.y[idx], self.u[idx], self.v[idx])


def decode(path: Path, p: Probe) -> Planes:
    w, h = p.width, p.height
    raw = run(
        ["ffmpeg", "-v", "error", "-nostdin", "-i", str(path), "-map", f"0:{p.index}",
         "-an", "-sn", "-dn", "-fps_mode", "passthrough",
         "-f", "rawvideo", "-pix_fmt", "yuv420p", "-"],
        capture_output=True,
    ).stdout
    fs = w * h * 3 // 2
    n = len(raw) // fs
    flat = np.frombuffer(raw, np.uint8, count=n * fs).reshape(n, fs)
    y = flat[:, : w * h].reshape(n, h, w).copy()
    u = flat[:, w * h : w * h * 5 // 4].reshape(n, h // 2, w // 2).copy()
    v = flat[:, w * h * 5 // 4 :].reshape(n, h // 2, w // 2).copy()
    return Planes(y, u, v)


