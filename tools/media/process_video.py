def destinations(item: Item, free_ids: set[str]) -> tuple[Path, Path, list[Path]]:
    """(video, poster, stale copies to remove). The catalog decides free vs Premium."""
    bundled = (BUNDLED_DIR / f"{item.id}.mp4", BUNDLED_DIR / f"{item.id}.jpg")
    remote = (CONTENT_DIR / "videos" / "paysages" / f"{item.id}.mp4",
              CONTENT_DIR / "images" / "paysages" / f"{item.id}.jpg")
    test = (TEST_DIR / "videos" / "paysages" / f"{item.id}.mp4",
            TEST_DIR / "images" / "paysages" / f"{item.id}.jpg")
    if item.test_only:
        return (*test, [*bundled, *remote])
    if item.id in free_ids:
        return (*bundled, [*remote, *test])
    return (*remote, [*bundled, *test])


def process(item: Item, free_ids: set[str], sheets: Path | None, check_only: bool) -> dict:
    t0 = time.time()
    video, poster, stale = destinations(item, free_ids)
    src = REPO / item.source
    p = probe(src)
    result: dict = {"id": item.id, "source": item.source,
                    "video": str(video.relative_to(REPO)), "poster": str(poster.relative_to(REPO))}
    if not check_only:
        pl = decode(src, p)
        result["source_frames"] = pl.n
        result["source_size"] = [p.width, p.height]
        result["source_join_diff"] = round(frame_diff(pl.y[0], pl.y[-1]), 3)
        src_d = consecutive_diffs(pl.y)
        result["source_consecutive_median"] = round(float(np.median(src_d)), 3)
        if item.crop_aspect:
            pl = crop_to_aspect(pl, item.crop_aspect)
        if item.grade:
            grade(pl, **item.grade)
        means = luma_means(pl.y)
        fl = detect_flashes(means, p.fps)
        if not item.crop_aspect and not item.grade:
            # Abrupt changes that are not flashes (generation glitches, cuts): reported so
            # that a human can exclude them (span), never silently looped.
            med = float(np.median(src_d))
            result["source_jumps"] = [
                [i, i + 1, round(float(x), 2)] for i, x in enumerate(src_d)
                if x > 4 * med and not fl.flags[max(0, i - 1) : i + 3].any()]
        small = small_luma(pl.y)
        seg = choose_segment(item, pl.n, p.fps, small, fl)
        result["segment"] = {"start": seg.start, "end": seg.end, "fade_frames": seg.fade,
                             "fade_s": round(seg.fade / float(p.fps), 3), "loop_frames": seg.loop,
                             "window_cost": round(seg.cost, 3)}
        if item.remove_flashes:
            seg_y = pl.y[seg.start : seg.start + seg.loop]
            jump_before = max_luma_jump(seg_y)
            removed = remove_flash_frames(pl, fl, seg.start, seg.end)
            after = luma_means(pl.y)
            loop_means = after[seg.start : seg.start + seg.loop]
            result["flashes"] = {
                "mode": "removed",
                "baseline_median": round(float(np.median(fl.baseline)), 1),
                "events_in_source": len(fl.events()),
                "replaced": removed,
                "frames_replaced": sum(r["frames"][1] - r["frames"][0] + 1 for r in removed),
                "max_luma_jump_before": round(jump_before, 2),
                "max_luma_jump_after": round(max_luma_jump(pl.y[seg.start : seg.start + seg.loop]), 2),
                "max_excess_after": round(float((loop_means - fl.baseline[seg.start : seg.start + seg.loop]).max()), 2),
                "fade_windows_quiet": bool(fl.quiet[seg.start : seg.start + seg.fade].all()
                                           and fl.quiet[seg.start + seg.loop : seg.end].all()),
            }
        if item.soften_flashes:
            events = [(a, b, round(float(means[a:b].max()), 1)) for a, b in fl.events()]
            softened = soften_flashes(pl, fl, seg.start, seg.end)
            after = luma_means(pl.y)
            result["flashes"] = {
                "baseline_median": round(float(np.median(fl.baseline)), 1),
                "events": [{"frames": [a, b - 1], "peak_luma_before": pk,
                            "peak_luma_after": round(float(after[a:b].max()), 1),
                            "in_loop": a < seg.end and b > seg.start} for a, b, pk in events],
                "frames_softened": len(softened),
                "fade_windows_quiet": bool(fl.quiet[seg.start : seg.start + seg.fade].all()
                                           and fl.quiet[seg.start + seg.loop : seg.end].all()),
            }
        out = crossfade(pl, seg)
        result["master"] = {"join_diff": round(frame_diff(out.y[0], out.y[-1]), 3),
                            "consecutive_median": round(float(np.median(consecutive_diffs(out.y))), 3)}
        video.parent.mkdir(parents=True, exist_ok=True)
        crf, size = encode_under_budget(out, p.fps, p, video, item)
        result["crf"] = crf
        result["poster_vs_frame0"] = write_poster(video, poster, p.space)
        for old in stale:
            if old.exists():
                old.unlink()
    else:
        result["poster_vs_frame0"] = poster_error(video, poster, p.space)
    m = measure(video)
    planes = m.pop("planes")
    result["output"] = m
    result["poster_bytes"] = poster.stat().st_size
    if sheets is not None:
        n = planes.n
        sheet(planes, [n - 3, n - 2, n - 1, 0, 1, 2], p.space, sheets / f"{item.id}-join.png")
        fade = result.get("segment", {}).get("fade_frames", 24)
        sheet(planes, [0, fade // 4, fade // 2, 3 * fade // 4, fade - 1, fade, n // 2],
              p.space, sheets / f"{item.id}-fade.png", width=160)
    result["seconds_spent"] = round(time.time() - t0, 1)
    return result


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--only", nargs="*", help="landscape ids to process")
    ap.add_argument("--check-only", action="store_true", help="re-measure the existing outputs")
    ap.add_argument("--sheets", type=Path, help="write contact sheets (join, fade) here")
    ap.add_argument("--report", type=Path, help="write the measurements as JSON")
    args = ap.parse_args()

    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    free_ids = {p["id"] for p in catalog["paysages"] if p.get("gratuit")}
    known = {p["id"] for p in catalog["paysages"]}
    items = [i for i in ITEMS if not args.only or i.id in args.only]
    for item in items:
        if item.id not in known:
            raise SystemExit(f"{item.id}: not a landscape of the catalog")

    results = []
    for item in items:
        r = process(item, free_ids, args.sheets, args.check_only)
        o = r["output"]
        print(f"{item.id}: {o['frames']} frames ({o['seconds']} s @ {o['fps']} fps, "
              f"{o['size'][0]}x{o['size'][1]}), {o['bytes'] / 1e6:.2f} MB ({o['kbit_s']} kbit/s)"
              + (f", CRF {r['crf']}" if "crf" in r else ""))
        print(f"  join {o['join_diff']} vs consecutive median {o['consecutive_median']} "
              f"(p95 {o['consecutive_p95']}, max {o['consecutive_max']}, steps into key frames "
              f"{o['keyframe_step_mean']}); poster {r['poster_bytes'] / 1e3:.0f} kB, "
              f"vs frame 0: {r['poster_vs_frame0']}")
        if "master" in r:
            print(f"  before encoding: join {r['master']['join_diff']} vs consecutive median "
                  f"{r['master']['consecutive_median']}")
        if r.get("source_jumps"):
            print(f"  source jumps (not flashes): {r['source_jumps']}")
        if "segment" in r:
            s = r["segment"]
            print(f"  source frames {s['start']}..{s['end'] - 1}, fade {s['fade_frames']} frames "
                  f"({s['fade_s']} s), raw join was {r['source_join_diff']}")
        if "flashes" in r and r["flashes"].get("mode") == "removed":
            f = r["flashes"]
            for e in f["replaced"]:
                print(f"  flash {e['frames']} removed: luma {e['peak_luma_before']} -> {e['peak_luma_after']}"
                      f" (cross-fade of frames {e['quiet_before']} and {e['quiet_after']})")
            print(f"  {f['frames_replaced']} frames replaced; max frame-to-frame luma jump in the loop "
                  f"{f['max_luma_jump_before']} -> {f['max_luma_jump_after']} (encoded, join included: "
                  f"{o['max_luma_jump']}); max excess over the baseline {f['max_excess_after']}; "
                  f"fade windows flash-free: {f['fade_windows_quiet']}")
        elif "flashes" in r:
            f = r["flashes"]
            for e in f["events"]:
                print(f"  flash {e['frames']}: luma {e['peak_luma_before']} -> {e['peak_luma_after']}"
                      f"{'' if e['in_loop'] else ' (outside the loop)'}")
            print(f"  baseline luma {f['baseline_median']}, fade windows flash-free: {f['fade_windows_quiet']}")
        results.append(r)

    if not args.check_only:
        manifest = write_remote_manifest()
        print(f"{REMOTE_MANIFEST.relative_to(REPO)}: {manifest}")
    if args.report:
        args.report.write_text(json.dumps(results, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
