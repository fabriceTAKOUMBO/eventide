#!/usr/bin/env python3
"""Seamless landscape video loops for Eventide: loop, no audio, H.264, poster.

Turns a raw landscape video (generated by a video model, or third-party test
material) into what the app plays behind its glass panels:

  * a **seamless loop**: the last F frames are cross-faded over the first F
    frames, so the output has N - F frames and frame L-1 flows into frame 0
    exactly as two consecutive source frames do;
  * **no audio** (the app's own mixer plays the sounds), no metadata;
  * H.264 High profile, yuv420p, constant frame rate (the source rate), a key
    frame every 2 s, no B-frames (no edit list, no reordering delay: frame 0 is
    the first decoded frame), ``+faststart``; the CRF is the lowest one that
    keeps the file under ``max_bytes`` (2.5 MB by default);
  * a **poster** JPEG that is the encoded loop's own frame 0 (decoded back from
    the MP4), so that the poster -> video swap in the app is pixel-identical.

Optional steps, per item (see ITEMS):
  * ``crop_aspect``: centre crop to 9:16 (never upscaled, never letterboxed);
  * ``grade``: dim (gain + gamma on luma) and desaturate (chroma scale);
  * ``soften_flashes``: lightning flashes are detected as spikes of the frame
    mean luma above a rolling 20th percentile (+-2 s) and their brightness rise
    is compressed (soft knee to +15 % of the baseline, at most +6 % per frame),
    pixel by pixel against a per-pixel baseline (median of the nearest quiet
    frames), so that only what the flash brightened is dimmed;
  * ``remove_flashes``: lightning is **removed** from the picture (the app draws
    its own flashes, in sync with the thunder: contract § 11). Every frame of a
    flash (with a 2-frame margin) is replaced by the cross-fade of the two quiet
    frames around it, on Y, U and V: the sky glow and the bolts disappear, the
    drops on the glass stay where they are. Used with the ``fewest-flashes``
    segment;
  * ``segment``: ``full`` (whole source, or the ``span`` of source frames given
    when the source has a defect, e.g. a generation discontinuity), ``avoid-flashes`` (longest loop whose
    two fade windows contain no flash, with a 2-frame margin, so that a flash is
    never cut in half by the cross-fade), ``fewest-flashes`` (loop of at least
    ``min_loop_s`` whose fade windows are quiet and that holds the fewest flash
    frames, so that the fewest frames are replaced) or ``best-match`` (loop length in a
    range, fade windows chosen where the two moments look most alike on a
    blurred luma, to avoid ghosting).

Everything is done on the decoded yuv420p planes (no RGB round trip), with
numpy; ffmpeg only decodes and encodes. The script then decodes each output and
measures the loop join (mean absolute luma difference between the last and the
first frame) against the consecutive-frame differences of the whole loop.

Usage (from the repository root):
  python3 tools/media/process_video.py                     # every item
  python3 tools/media/process_video.py --only pluie-ville
  python3 tools/media/process_video.py --check-only        # re-measure outputs
  python3 tools/media/process_video.py --sheets /tmp/sheets --report r.json

Media files are untrusted input: they are only read through ffmpeg/ffprobe.
"""

