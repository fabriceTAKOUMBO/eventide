def encode(pl: Planes, fps: Fraction, p: Probe, crf: int, out: Path, copies: int) -> int:
    w, h = pl.size
    gop = int(round(GOP_SECONDS * fps))
    cmd = [
        "ffmpeg", "-v", "error", "-nostdin", "-y",
        "-f", "rawvideo", "-pix_fmt", "yuv420p", "-s", f"{w}x{h}", "-r", str(fps), "-i", "-",
        "-an", "-sn", "-dn", "-map_metadata", "-1",
        "-c:v", "libx264", "-preset", X264_PRESET, "-crf", str(crf),
        "-profile:v", "high", "-level:v", "4.0", "-pix_fmt", "yuv420p", "-bf", "0",
        "-threads", str(THREADS),
        "-x264-params", f"keyint={gop}:min-keyint={gop}:scenecut=0:bframes=0:open-gop=0",
        "-color_range", "tv", "-colorspace", matrix_of(p.space),
        "-color_primaries", "bt709", "-color_trc", "bt709",
        "-movflags", "+faststart", "-fflags", "+bitexact", "-flags:v", "+bitexact",
        "-metadata:s:v:0", "handler_name=Eventide landscape", "-metadata:s:v:0", "language=und",
        str(out),
    ]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    assert proc.stdin is not None
    for _ in range(copies):
        for i in range(pl.n):
            proc.stdin.write(pl.y[i].tobytes())
            proc.stdin.write(pl.u[i].tobytes())
            proc.stdin.write(pl.v[i].tobytes())
    proc.stdin.close()
    if proc.wait() != 0:
        raise SystemExit(f"ffmpeg failed for {out}")
    return out.stat().st_size


def encode_under_budget(pl: Planes, fps: Fraction, p: Probe, out: Path, item: Item) -> tuple[int, int]:
    """Lowest CRF whose file fits in item.max_bytes (binary search)."""
    lo, hi = CRF_MIN, CRF_MAX
    best: tuple[int, int] | None = None
    last = None
    while lo <= hi:
        mid = (lo + hi) // 2
        size = encode(pl, fps, p, mid, out, item.copies)
        last = mid
        if size <= item.max_bytes:
            best, hi = (mid, size), mid - 1
        else:
            lo = mid + 1
    if best is None:
        raise SystemExit(f"{item.id}: does not fit in {item.max_bytes} bytes at CRF {CRF_MAX}")
    if last != best[0]:
        encode(pl, fps, p, best[0], out, item.copies)
    return best


def rgb_frame0(video: Path, space: str) -> np.ndarray:
    p = probe(video)
    raw = run(
        ["ffmpeg", "-v", "error", "-nostdin", "-i", str(video), "-map", f"0:{p.index}",
         "-frames:v", "1",
         "-vf", f"scale=in_color_matrix={sws_matrix(space)}:in_range=tv:out_range=pc:"
                "flags=bilinear+accurate_rnd+full_chroma_int",
         "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
        capture_output=True,
    ).stdout
    return np.frombuffer(raw, np.uint8).reshape(p.height, p.width, 3)


def write_poster(video: Path, poster: Path, space: str) -> dict:
    rgb = rgb_frame0(video, space)
    poster.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(rgb, "RGB").save(poster, "JPEG", quality=POSTER_QUALITY, optimize=True,
                                     subsampling="4:2:0", progressive=False)
    return poster_error(video, poster, space, rgb)


def poster_error(video: Path, poster: Path, space: str, rgb: np.ndarray | None = None) -> dict:
    if rgb is None:
        rgb = rgb_frame0(video, space)
    with Image.open(poster) as im:
        jpg = np.asarray(im.convert("RGB"))
    d = np.abs(jpg.astype(np.int16) - rgb)
    return {"mean_abs": round(float(d.mean()), 3), "p99_abs": int(np.percentile(d, 99)),
            "size": [int(rgb.shape[1]), int(rgb.shape[0])]}


def measure(video: Path) -> dict:
    p = probe(video)
    pl = decode(video, p)
    d = consecutive_diffs(pl.y)
    join = frame_diff(pl.y[0], pl.y[-1])
    med = float(np.median(d))
    gop = int(round(GOP_SECONDS * p.fps))
    # Step into each key frame (x264 key frames are sharper than the P-frames before
    # them): the join, which is also a step into a key frame, is compared to these.
    key_steps = [float(d[k - 1]) for k in range(gop, pl.n, gop)]
    return {
        "frames": pl.n,
        "seconds": round(pl.n / float(p.fps), 3),
        "fps": str(p.fps),
        "size": [p.width, p.height],
        "bytes": video.stat().st_size,
        "kbit_s": round(video.stat().st_size * 8 / 1000 / (pl.n / float(p.fps)), 1),
        "join_diff": round(join, 3),
        "consecutive_median": round(med, 3),
        "consecutive_p95": round(float(np.percentile(d, 95)), 3),
        "consecutive_max": round(float(d.max()), 3),
        "join_over_median": round(join / med, 2) if med else None,
        "keyframe_step_mean": round(float(np.mean(key_steps)), 3) if key_steps else None,
        "mean_luma": round(float(luma_means(pl.y).mean()), 1),
        # Largest frame-to-frame change of the mean luma, loop join included (lightning).
        "max_luma_jump": round(max_luma_jump(pl.y, circular=True), 2),
        "planes": pl,
    }


def yuv_to_rgb(y: np.ndarray, u: np.ndarray, v: np.ndarray, space: str) -> np.ndarray:
    """Preview conversion (limited range, nearest chroma) for the contact sheets."""
    kr, kb = (0.2126, 0.0722) if space == "bt709" else (0.299, 0.114)
    kg = 1 - kr - kb
    yy = (y.astype(np.float32) - 16) * 255 / 219
    uu = (np.repeat(np.repeat(u, 2, 0), 2, 1).astype(np.float32) - 128) * 255 / 224
    vv = (np.repeat(np.repeat(v, 2, 0), 2, 1).astype(np.float32) - 128) * 255 / 224
    r = yy + 2 * (1 - kr) * vv
    b = yy + 2 * (1 - kb) * uu
    g = (yy - kr * r - kb * b) / kg
    return np.clip(np.stack([r, g, b], -1), 0, 255).astype(np.uint8)


def sheet(pl: Planes, frames: list[int], space: str, path: Path, width: int = 240) -> None:
    tiles = []
    for i in frames:
        im = Image.fromarray(yuv_to_rgb(pl.y[i], pl.u[i], pl.v[i], space))
        h = round(im.height * width / im.width)
        tiles.append(im.resize((width, h), Image.LANCZOS))
    out = Image.new("RGB", (width * len(tiles) + 4 * (len(tiles) - 1), tiles[0].height), (255, 0, 255))
    for k, t in enumerate(tiles):
        out.paste(t, (k * (width + 4), 0))
    path.parent.mkdir(parents=True, exist_ok=True)
    out.save(path)


