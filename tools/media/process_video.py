def crop_to_aspect(pl: Planes, aspect: tuple[int, int]) -> Planes:
    """Centre crop to aspect (width:height), even dimensions, no scaling."""
    w, h = pl.size
    aw, ah = aspect
    if w * ah > h * aw:          # too wide: crop the sides
        nw = (h * aw // ah) // 2 * 2
        x0 = ((w - nw) // 2) // 2 * 2
        return Planes(pl.y[:, :, x0 : x0 + nw].copy(), pl.u[:, :, x0 // 2 : (x0 + nw) // 2].copy(),
                      pl.v[:, :, x0 // 2 : (x0 + nw) // 2].copy())
    nh = (w * ah // aw) // 2 * 2
    y0 = ((h - nh) // 2) // 2 * 2
    return Planes(pl.y[:, y0 : y0 + nh].copy(), pl.u[:, y0 // 2 : (y0 + nh) // 2].copy(),
                  pl.v[:, y0 // 2 : (y0 + nh) // 2].copy())


def grade(pl: Planes, gain: float, gamma: float, saturation: float,
          tint_u: float = 0.0, tint_v: float = 0.0) -> None:
    """Dims luma (gain x gamma curve on the 16-235 range) and scales chroma by the
    local luma gain times ``saturation`` (so dimming alone keeps the saturation)."""
    for i in range(pl.n):
        lum = np.clip((pl.y[i].astype(np.float32) - 16.0) / 219.0, 0.0, 1.0)
        out = gain * lum ** gamma
        pl.y[i] = np.clip(np.rint(16.0 + 219.0 * out), 0, 255)
        ratio = out / np.maximum(lum, 1.0 / 219.0)
        h2, w2 = pl.u.shape[1:]
        local = ratio[: h2 * 2, : w2 * 2].reshape(h2, 2, w2, 2).mean(axis=(1, 3))
        f = saturation * local
        pl.u[i] = np.clip(np.rint(128.0 + (pl.u[i] - 128.0) * f + tint_u), 0, 255)
        pl.v[i] = np.clip(np.rint(128.0 + (pl.v[i] - 128.0) * f + tint_v), 0, 255)


def luma_means(y: np.ndarray) -> np.ndarray:
    return y.reshape(y.shape[0], -1).mean(axis=1)


def consecutive_diffs(y: np.ndarray) -> np.ndarray:
    out = np.empty(y.shape[0] - 1)
    for i in range(y.shape[0] - 1):
        out[i] = np.abs(y[i + 1].astype(np.int16) - y[i]).mean()
    return out


def frame_diff(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.abs(a.astype(np.int16) - b).mean())


def rolling_percentile(x: np.ndarray, radius: int, q: float) -> np.ndarray:
    return np.array([np.percentile(x[max(0, i - radius) : i + radius + 1], q) for i in range(len(x))])


def runs(mask: np.ndarray) -> list[tuple[int, int]]:
    """[start, end) of each run of True."""
    out, start = [], None
    for i, m in enumerate(mask):
        if m and start is None:
            start = i
        elif not m and start is not None:
            out.append((start, i))
            start = None
    if start is not None:
        out.append((start, len(mask)))
    return out


@dataclass
class Flashes:
    baseline: np.ndarray
    excess: np.ndarray
    flags: np.ndarray
    quiet: np.ndarray

    def events(self) -> list[tuple[int, int]]:
        return runs(self.flags)


def detect_flashes(means: np.ndarray, fps: Fraction) -> Flashes:
    baseline = rolling_percentile(means, round(2 * fps), 20)
    excess = means - baseline
    flags = excess > FLASH_THRESHOLD
    near = flags.copy()
    for k in range(1, FLASH_MARGIN + 1):
        near[k:] |= flags[:-k]
        near[:-k] |= flags[k:]
    return Flashes(baseline, excess, flags, ~near)


def soften_flashes(pl: Planes, fl: Flashes, lo: int, hi: int) -> list[dict]:
    """Compresses the brightness rise of flash frames in [lo, hi) (in place)."""
    cap = FLASH_CAP * fl.baseline
    target = cap * np.tanh(np.maximum(fl.excess, 0) / cap)        # soft knee
    limited = target.copy()
    for i in range(1, len(limited)):                              # attack limiter
        limited[i] = min(limited[i], max(limited[i - 1], 0) + FLASH_MAX_RISE * fl.baseline[i])
    quiet_idx = np.flatnonzero(~fl.flags)
    report = []
    for i in range(lo, hi):
        reduce_by = fl.excess[i] - limited[i]
        if reduce_by <= 0.05:
            continue
        nearest = quiet_idx[np.argsort(np.abs(quiet_idx - i), kind="stable")[:FLASH_BASELINE_FRAMES]]
        base_y = np.median(pl.y[nearest].astype(np.float32), axis=0)
        y = pl.y[i].astype(np.float32)
        pos = np.maximum(y - base_y, 0.0)
        energy = float(pos.mean())
        if energy <= 0:
            continue
        t = min(1.0, reduce_by / energy)
        before = float(y.mean())
        pl.y[i] = np.clip(np.rint(y - t * pos), 0, 255)
        h2, w2 = pl.u.shape[1:]
        mask = np.clip(pos / 24.0, 0.0, 1.0)[: h2 * 2, : w2 * 2].reshape(h2, 2, w2, 2).mean(axis=(1, 3))
        for plane in (pl.u, pl.v):
            base_c = np.median(plane[nearest].astype(np.float32), axis=0)
            c = plane[i].astype(np.float32)
            plane[i] = np.clip(np.rint(c - t * mask * (c - base_c)), 0, 255)
        report.append({"frame": i, "luma_before": round(before, 2),
                       "luma_after": round(float(pl.y[i].mean()), 2),
                       "baseline": round(float(fl.baseline[i]), 2)})
    return report


def box_blur(x: np.ndarray, radius: int, passes: int = 2) -> np.ndarray:
    """Separable box blur (edges clamped); two passes approximate a Gaussian."""
    out = x.astype(np.float32)
    for _ in range(passes):
        for axis in (0, 1):
            pad = [(0, 0), (0, 0)]
            pad[axis] = (radius + 1, radius)
            c = np.cumsum(np.pad(out, pad, mode="edge"), axis=axis, dtype=np.float64)
            k = 2 * radius + 1
            out = ((np.take(c, range(k, c.shape[axis]), axis=axis)
                    - np.take(c, range(0, c.shape[axis] - k), axis=axis)) / k).astype(np.float32)
    return out


def dilate(mask: np.ndarray, radius: int) -> np.ndarray:
    out = mask.copy()
    for axis in (0, 1):
        grown = out.copy()
        for k in range(1, radius + 1):
            grown |= np.roll(out, k, axis=axis) | np.roll(out, -k, axis=axis)
        out = grown
    return out


def remove_flash_frames(pl: Planes, fl: Flashes, lo: int, hi: int) -> list[dict]:
    """Removes the lightning from every frame of [lo, hi) that is not quiet (a flash, with its
    margin), in place.

    Reference: the cross-fade ``ref`` of the nearest quiet frames before and after the flash.
    The difference ``d = frame - ref`` is split into a smooth part (blur: the sky glow, the
    light on the whole scene) and a detail part (drops sliding on the glass, rain, flicker of
    the city lights; but also the bolts and the drops lit by the flash):
      * the smooth part is dropped where it brightens (the glow);
      * the detail part is kept within +-FLASH_DETAIL_CAP where the flash does not reach (the
        city below keeps moving: a plain cross-fade would freeze the whole picture for up to
        2 s); where the glow exceeds FLASH_GLOW_FULL levels, and on the bolts and lit drops
        (dilated mask), only the reference is shown. The glow is estimated without the bolts,
        so no outline is left where a bolt was;
      * chroma follows the reference, with its fine detail kept within +-2 levels where
        the luma keeps its own detail.
    """
    quiet_idx = np.flatnonzero(fl.quiet)
    report = []
    for a, b in runs(~fl.quiet[lo:hi]):
        a, b = a + lo, b + lo
        before = quiet_idx[quiet_idx < a]
        after = quiet_idx[quiet_idx >= b]
        q0 = int(before[-1]) if before.size else None
        q1 = int(after[0]) if after.size else None
        if q0 is None and q1 is None:
            raise SystemExit("remove_flashes: no quiet frame in the source")
        q0 = q1 if q0 is None else q0
        q1 = q0 if q1 is None else q1
        peak = float(luma_means(pl.y[a:b]).max())
        masked = []
        for i in range(a, b):
            w = 0.0 if q1 == q0 else (i - q0) / (q1 - q0)

            def ref(plane, w=w, q0=q0, q1=q1):
                return (1 - w) * plane[q0].astype(np.float32) + w * plane[q1].astype(np.float32)

            ref_y = ref(pl.y)
            d = pl.y[i].astype(np.float32) - ref_y
            bolt = dilate(d - box_blur(d, FLASH_GLOW_RADIUS) > FLASH_BOLT_LEVEL, FLASH_BOLT_GROW)
            masked.append(float(bolt.mean()))
            # Glow estimated without the bolts (normalised convolution): no dark halo where a
            # bolt was.
            keep = (~bolt).astype(np.float32)
            smooth = box_blur(d * keep, FLASH_GLOW_RADIUS) / np.maximum(
                box_blur(keep, FLASH_GLOW_RADIUS), 1e-3)
            # Where the flash lights the scene, the reference only (no lit outline is left);
            # where it does not reach (the city below), the frame's own detail.
            own = np.clip(1.0 - np.maximum(smooth, 0.0) / FLASH_GLOW_FULL, 0.0, 1.0)
            detail = np.where(bolt, 0.0, own * np.clip(d - smooth, -FLASH_DETAIL_CAP, FLASH_DETAIL_CAP))
            pl.y[i] = np.clip(np.rint(ref_y + np.minimum(smooth, 0.0) + detail), 0, 255)
            h2, w2 = pl.u.shape[1:]
            own_c = (np.where(bolt, 0.0, own)[: h2 * 2, : w2 * 2]
                     .reshape(h2, 2, w2, 2).min(axis=(1, 3)))
            for plane in (pl.u, pl.v):
                ref_c = ref(plane)
                dc = plane[i].astype(np.float32) - ref_c
                dc -= box_blur(dc, max(1, FLASH_GLOW_RADIUS // 2))
                plane[i] = np.clip(np.rint(ref_c + own_c * np.clip(dc, -2.0, 2.0)), 0, 255)
        report.append({"frames": [a, b - 1], "quiet_before": q0, "quiet_after": q1,
                       "peak_luma_before": round(peak, 1),
                       "peak_luma_after": round(float(luma_means(pl.y[a:b]).max()), 1),
                       "bolt_mask_max_pct": round(100 * max(masked), 2)})
    return report


def max_luma_jump(y: np.ndarray, circular: bool = False) -> float:
    """Largest frame-to-frame change of the mean luma (a flash is a jump of tens of levels)."""
    m = luma_means(y)
    if circular:
        m = np.concatenate([m, m[:1]])
    return float(np.abs(np.diff(m)).max())


def small_luma(y: np.ndarray, block: int = 16) -> np.ndarray:
    n, h, w = y.shape
    hb, wb = h // block, w // block
    out = np.empty((n, hb, wb), np.float32)
    for i in range(n):
        out[i] = y[i, : hb * block, : wb * block].reshape(hb, block, wb, block).mean(axis=(1, 3))
    return out


def window_cost(small: np.ndarray, a: int, loop: int, fade: int) -> float:
    """How different the two cross-faded windows are (blurred luma)."""
    return float(np.abs(small[a : a + fade] - small[a + loop : a + loop + fade]).mean())


@dataclass
class Segment:
    start: int          # first source frame used
    fade: int           # cross-fade length (frames)
    loop: int           # output length (frames)
    cost: float

    @property
    def end(self) -> int:
        return self.start + self.loop + self.fade


def choose_segment(item: Item, n: int, fps: Fraction, small: np.ndarray, fl: Flashes) -> Segment:
    fade = round(item.fade_s * fps)
    if item.segment == "full":
        lo, hi = item.span or (0, n)
        return Segment(lo, fade, hi - lo - fade, window_cost(small, lo, hi - lo - fade, fade))
    if item.span:
        raise SystemExit(f"{item.id}: span is only used by the full segment mode")
    if item.segment == "fewest-flashes":
        # Every flash frame of the loop is replaced (remove_flashes): the fewest such frames,
        # then the longest loop, then the most alike fade windows. A flash run must have a
        # quiet frame on each side inside the segment (the cross-fade window is quiet).
        min_fade = round((item.min_fade_s or item.fade_s) * fps)
        min_loop = round(item.min_loop_s * fps)
        noisy = np.concatenate([[0], np.cumsum(~fl.quiet)])
        best_key, best = None, None
        for f in range(fade, min_fade - 1, -1):
            ok = [p for p in range(n - f + 1) if fl.quiet[p : p + f].all()]
            for a in ok:
                for c in ok:
                    loop = c - a
                    if loop < max(min_loop, f):
                        continue
                    count = int(noisy[a + loop] - noisy[a])
                    key = (count, -loop, -f)
                    if best_key is not None and key > best_key:
                        continue
                    cand = Segment(a, f, loop, window_cost(small, a, loop, f))
                    if best_key is None or key < best_key or cand.cost < best.cost:
                        best_key, best = key, cand
        if best is None:
            raise SystemExit(f"{item.id}: no loop of {item.min_loop_s} s with quiet fade windows")
        return best
    if item.segment == "avoid-flashes":
        min_fade = round((item.min_fade_s or item.fade_s) * fps)
        min_loop = round(item.min_loop_s * fps)
        best: Segment | None = None
        for f in range(fade, min_fade - 1, -1):
            ok = [p for p in range(n - f + 1) if fl.quiet[p : p + f].all()]
            pairs = [(c - a, a) for a in ok for c in ok if c - a >= max(min_loop, f)]
            if not pairs:
                continue
            longest = max(loop for loop, _ in pairs)
            if best is not None and (longest, f) <= (best.loop, best.fade):
                continue
            # Longest loop for this fade; ties broken by the most alike windows.
            cand = min((Segment(a, f, loop, window_cost(small, a, loop, f))
                        for loop, a in pairs if loop == longest), key=lambda s: s.cost)
            best = cand
        if best is None:
            raise SystemExit(f"{item.id}: no flash-free fade windows")
        return best
    if item.segment == "best-match":
        lo, hi = (round(s * fps) for s in item.loop_range_s or (n / fps / 2, n / fps))
        best = None
        for loop in range(lo, min(hi, n - fade) + 1):
            d = np.abs(small[: n - loop] - small[loop:]).mean(axis=(1, 2))
            c = np.concatenate([[0.0], np.cumsum(d)])
            starts = np.arange(0, n - loop - fade + 1)
            if len(starts) == 0:
                continue
            costs = (c[starts + fade] - c[starts]) / fade
            a = int(starts[np.argmin(costs)])
            cand = Segment(a, fade, loop, float(costs.min()))
            if best is None or cand.cost < best.cost:
                best = cand
        if best is None:
            raise SystemExit(f"{item.id}: source too short for the loop range")
        return best
    raise SystemExit(f"{item.id}: unknown segment mode {item.segment}")


def crossfade(pl: Planes, seg: Segment) -> Planes:
    """Output frame j < F = blend of source frames start+L+j (weight 1-w) and start+j (w),
    w = (j+1)/(F+1); frames F..L-1 are the source as is. Frame L-1 -> frame 0 is then
    source frame start+L-1 -> (almost) start+L: a natural step."""
    s, f, loop = seg.start, seg.fade, seg.loop
    out = pl.take(slice(s, s + loop))
    out = Planes(out.y.copy(), out.u.copy(), out.v.copy())
    for j in range(f):
        w = (j + 1) / (f + 1)
        for dst, src in ((out.y, pl.y), (out.u, pl.u), (out.v, pl.v)):
            a = src[s + loop + j].astype(np.float32)
            b = src[s + j].astype(np.float32)
            dst[j] = np.clip(np.rint((1 - w) * a + w * b), 0, 255)
    return out


